/* ============================================================
 * html5_entities.h — HTML 字符实体解码 / 属性值归一化
 * ------------------------------------------------------------
 * 浏览器在 HTML 属性值解析阶段会先解字符实体，再做 URL / JS 解析。
 * 这里把这一步单独抽出来，供规则层复用，避免规则文件里塞满解码细节。
 *
 * 覆盖：
 *   1) 字符实体解码
 *        &#14;  -> U+000E（控制字符）    &#x09; -> TAB    &#106; -> 'j'
 *        命名实体 &colon; / &Tab; / &NewLine; ...（分号必需、大小写敏感）
 *   2) 空白 / 控制字符折叠
 *        jav\tascript: -> javascript:     前导空白、null 一律丢掉
 *
 * 注意分工：实体解码是 **HTML 解析器**的职责，与 JS 引擎自己的
 * \uXXXX / \xXX 转义（见 src/js/js_tokens.rl）不是一回事 ——
 * 前者发生在 JS 看到文本之前，后者由 JS 引擎做。所以这里只处理实体。
 * ============================================================ */
#ifndef HTML5_ENTITIES_H
#define HTML5_ENTITIES_H

/* 只解实体，保留空白与大小写。写入 out（cap 字节，含结尾 '\0'），
 * 返回解码后的字节长度。
 * 用途：把属性值还原成"浏览器交给 JS 引擎的样子"，再做 JS 语义分析。
 * 注意：只适用于属性值 —— <script>/<style> 是 raw text，浏览器不解
 * 其中的实体，那类内容不要过这个函数。 */
int h5_decode_entities(const char* s, int len, char* out, int cap);

/* ------------------------------------------------------------
 * 归一化流：实体解码 + 空白/控制字符折叠 + 转小写，惰性逐字节读取。
 * 用途：在"浏览器眼里的 URL"上做前缀匹配（如 javascript:）。
 * 做成惰性是为了不受缓冲区长度限制 —— 前面塞几百个空格也折叠得掉。
 * ------------------------------------------------------------ */
typedef struct {
    const char* p;
    int n;
    char q[4];     /* 单个实体解码出的 UTF-8 字节缓冲 */
    int qi, qn;
} H5UrlNorm;

void h5_norm_init(H5UrlNorm* st, const char* s, int len);

/* 取下一个归一化字节（已小写）；返回 0 表示输入结束 */
int h5_norm_next(H5UrlNorm* st);

#endif /* HTML5_ENTITIES_H */
