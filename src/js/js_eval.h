/* ============================================================
 * js_eval.h — JS 常量折叠求值器（jsfuck 拦截，阶段 1）
 * ------------------------------------------------------------
 * 对 lex_js 的 token 流做递归下降解析 + 常量折叠求值，把 jsfuck
 * 的 []!+() 运算还原成字符串/数字/布尔/函数引用，检测"动态构造
 * 代码"（Function(...) 调用）这类危险形态。
 *
 * 只覆盖 jsfuck 用到的表达式子集，遇到变量等不可求值结构时该
 * 分支返回"不可求值"（保守：不判危险、也不误报）。
 * ============================================================ */
#ifndef JS_EVAL_H
#define JS_EVAL_H

#include "js_tokens.h"

/* 对 token 流做常量折叠求值，检测 jsfuck 式混淆。
 * 返回 1 = 检出危险（如 Function("...") 动态构造代码），0 = 未检出。 */
int js_eval_dangerous(const JsTok* toks, int n);

#endif /* JS_EVAL_H */
