/* ============================================================
 * utf8.h — Unicode 码点 -> UTF-8 字节
 * ------------------------------------------------------------
 * HTML 实体解码（&#x4E2D;）和 JS 转义还原（\u4E2D / \xE9）都要把解析
 * 出来的码点写回字节流，这里提供共用实现，避免各模块各抄一份。
 * ============================================================ */
#ifndef RAGEL_UTF8_H
#define RAGEL_UTF8_H

/* 把码点 cp 编码成 UTF-8 写入 out（需 4 字节空间），返回写入字节数。
 * cp 超出 Unicode 范围时按 U+FFFD 处理，避免写出非法序列。 */
int utf8_put(char* out, int cp);

#endif /* RAGEL_UTF8_H */
