/* ============================================================
 * esc.h — 十六进制位与 \u 转义解析
 * ------------------------------------------------------------
 * 纯字符层的解析，跟具体语言无关，谁要解转义都来这儿拿：
 *   hex_val      十六进制字符 -> 数值
 *   u_esc_parse  JS/JSON 风格的 \uXXXX / \u{XXXXXX} -> 码点
 * 码点要变成字节用 utf8.h 的 utf8_put()。
 *
 * 注意分寸：这里只认"转义长什么样"。\u 出现在标识符里、字符串字面量
 * 里、还是当行继续，以及 \x \n \0 这些同族转义怎么解，都是各语言
 * 自己的规定，不在这层 —— 见 src/js/js_tokens.rl 的 js_decode_*。
 * ============================================================ */
#ifndef RAGEL_ESC_H
#define RAGEL_ESC_H

/* 十六进制字符 -> 数值；不是十六进制字符返回 -1 */
int hex_val(char c);

/* 解析 \uXXXX 或 \u{XXXXXX} 形式的转义（p 指向反斜杠）。
 * 成功返回码点并令 *adv = 消耗字节数；非法返回 -1 且不改动 *adv。
 * 码点超出 U+10FFFF 也视为非法。 */
int u_esc_parse(const char* p, int len, int* adv);

#endif /* RAGEL_ESC_H */
